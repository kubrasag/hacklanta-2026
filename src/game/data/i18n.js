let current = 'en';

export function setUiLanguage(code) {
  current = STRINGS[code] ? code : 'en';
  document.documentElement.lang = current;
}

export function uiLanguage() {
  return current;
}

export function t(key, vars = {}) {
  const value = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return typeof value === 'string' ? fill(value, vars) : value;
}

// "in Spanish", written the way each help language says it
export function langName(code) {
  return STRINGS[current].langNames[code];
}
